/** Cell coordinates (column, row from the top) of every filled block in `text`, plus the grid width. */
export function layoutBlocks(text: string, tracking = 1): { cells: Array<[number, number]>; cols: number } {
  const cells: Array<[number, number]> = [];
  const chars = [...text.toUpperCase()];
  chars.forEach((ch, i) => {
    const glyph = G[ch] ?? G[" "];
    const x0 = i * (GLYPH_W + tracking);
    glyph.forEach((row, r) => {
      [...row].forEach((c, col) => {
        if (c === "#") cells.push([x0 + col, r]);
      });
    });
  });
  const cols = chars.length ? chars.length * (GLYPH_W + tracking) - tracking : 0;
  return { cells, cols };
}
