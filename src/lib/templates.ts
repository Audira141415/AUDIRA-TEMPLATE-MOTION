function generateWordTimestamps(text: string, startSec: number, durationSec: number) {
  const words = text.split(' ').filter(Boolean);
  const wordDuration = durationSec / Math.max(words.length, 1);
  return words.map((word, index) => ({
    word,
    start: Number((startSec + index * wordDuration).toFixed(2)),
    end: Number((startSec + (index + 1) * wordDuration).toFixed(2)),
  }));
}

